const reviewedInspection = (
  id: string,
  infrastructureId: string,
  damageLevel: Inspection['damageLevel'],
  peopleNeedingSupport: number,
  estimatedOccupants: number,
): Inspection => ({
  id,
  infrastructureId,
  status: 'reviewed',
  access: 'accessible',
  observation: damageLevel === 'none' ? 'no_damage_observed' : 'damage_observed',
  damageLevel,
  element: damageLevel === 'none' ? 'unknown' : 'wall',
  condition: damageLevel === 'none' ? 'none' : 'crack',
  observability: 'good',
  viewType: 'exterior',
  notes:
    damageLevel === 'none'
      ? 'Sin daño visible en las superficies observadas.'
      : 'Fisura visible registrada para revisión profesional.',
  estimatedOccupants,
  peopleNeedingSupport,
  needs: peopleNeedingSupport > 0 ? ['shelter'] : [],
  mediaIds: [],
  updatedAt: '2038-01-19T10:00:00.000Z',
  reviewedAt: '2038-01-19T10:00:00.000Z',
});

